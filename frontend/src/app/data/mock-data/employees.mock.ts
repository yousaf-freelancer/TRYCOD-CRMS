/** Standard Indian salary split: basic 40%, HRA 20%, conveyance ₹1,600, rest special allowance. */
export function salaryStructureFor(employeeId: string, gross: number): SalaryStructure {
  const basic = Math.round(gross * 0.4);
  const hra = Math.round(gross * 0.2);
  const conveyance = 1600;
  const specialAllowance = gross - basic - hra - conveyance;
  return {
    employeeId,
    basic,
    hra,
    conveyance,
    specialAllowance,
    pf: Math.min(Math.round(basic * 0.12), 1800),
    esi: gross <= 21000 ? Math.round(gross * 0.0075) : 0,
    professionalTax: gross >= 12000 ? 200 : 0,
    tds: gross >= 100000 ? Math.round(gross * 0.08) : gross >= 60000 ? Math.round(gross * 0.03) : 0,
  };
}

